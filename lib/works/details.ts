export type WorkDetailSection = {
  title: string;
  label: string;
  items: string[];
};

export type WorkDetailHero = {
  src: string;
  alt: string;
  mediaType?: "image" | "gif";
  caption?: string;
};

export type WorkDetail = {
  id: string;
  period: string;
  title: string;
  summary: string;
  tags: string[];
  hero?: WorkDetailHero;
  gallery?: WorkDetailHero[];
  overview: string;
  sections: WorkDetailSection[];
};

function pocGallery(pocId: string): WorkDetailHero[] {
  return [1, 2, 3, 4, 5].map((n) => ({
    src: `/works/${pocId}-${n}.png`,
    alt: `데모 ${n}`,
  }));
}

function standardSections(
  problem: string[],
  role: string[],
  approach: string[],
  stack: string[],
  outcome: string[],
): WorkDetailSection[] {
  return [
    { label: "01", title: "Problem", items: problem },
    { label: "02", title: "Role & Scope", items: role },
    { label: "03", title: "Approach", items: approach },
    { label: "04", title: "Tech Stack", items: stack },
    { label: "05", title: "Outcome", items: outcome },
  ];
}

